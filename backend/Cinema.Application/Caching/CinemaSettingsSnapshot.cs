using Cinema.Domain.Entities;
using Cinema.Domain.Enums;

namespace Cinema.Application.Caching;

public sealed record CinemaSettingsSnapshot(
    string Name,
    string Address,
    string? Phone,
    string? Email,
    string? TaxCode,
    string? LogoUrl,
    TimeOnly? OpeningTime,
    TimeOnly? ClosingTime,
    decimal PointsPerAmount,
    decimal CancelRefundPercent,
    int CancelDeadlineHours,
    int StopSellingMinutesBefore,
    int HoldDurationMinutes,
    int CheckInOpenMinutes,
    SeatGapRuleMode SeatGapRuleMode,
    int RoomBufferMinutes,
    int MaxSeatsPerBooking,
    int MaxComboQuantity,
    int LoyaltyWindowMonths,
    int MovieEndGraceDays,
    int ShowtimeLookaheadDays,
    int SchedulerStepMinutes,
    int SchedulerMinSameMovieGapMinutes,
    int SchedulerHeatLookbackDays,
    double SchedulerHeatSalesWeight,
    double SchedulerHeatRatingWeight,
    double SchedulerMaxRating,
    decimal TicketPriceRoundingStep,
    decimal DynamicPricingMaxIncreasePercent,
    decimal DynamicPricingMaxDecreasePercent,
    decimal MinTicketPrice,
    int SalesPaceCustomMarkMinutes,
    int SuggestionHighOccupancyPercent,
    int SuggestionLowOccupancyPercent,
    int SuggestionMinShowtimes,
    int SuggestionLookbackDays,
    bool DailyClosingAllowOverride,
    decimal TicketVatPercent,
    decimal ComboVatPercent,
    decimal GiftCardVatPercent,
    decimal MembershipVatPercent,
    int InvoiceRequestWindowDays,
    decimal[] GiftCardDenominations,
    decimal GiftCardMinAmount,
    decimal GiftCardMaxAmount,
    int GiftCardValidityMonths,
    int GiftCardRefundExtensionDays
)
{
    public static CinemaSettingsSnapshot From(CinemaSettings s) =>
        new(
            s.Name,
            s.Address,
            s.Phone,
            s.Email,
            s.TaxCode,
            s.LogoUrl,
            s.OpeningTime,
            s.ClosingTime,
            s.PointsPerAmount,
            s.CancelRefundPercent,
            s.CancelDeadlineHours,
            s.StopSellingMinutesBefore,
            s.HoldDurationMinutes,
            s.CheckInOpenMinutes,
            s.SeatGapRuleMode,
            s.RoomBufferMinutes,
            s.MaxSeatsPerBooking,
            s.MaxComboQuantity,
            s.LoyaltyWindowMonths,
            s.MovieEndGraceDays,
            s.ShowtimeLookaheadDays,
            s.SchedulerStepMinutes,
            s.SchedulerMinSameMovieGapMinutes,
            s.SchedulerHeatLookbackDays,
            s.SchedulerHeatSalesWeight,
            s.SchedulerHeatRatingWeight,
            s.SchedulerMaxRating,
            s.TicketPriceRoundingStep,
            s.DynamicPricingMaxIncreasePercent,
            s.DynamicPricingMaxDecreasePercent,
            s.MinTicketPrice,
            s.SalesPaceCustomMarkMinutes,
            s.SuggestionHighOccupancyPercent,
            s.SuggestionLowOccupancyPercent,
            s.SuggestionMinShowtimes,
            s.SuggestionLookbackDays,
            s.DailyClosingAllowOverride,
            s.TicketVatPercent,
            s.ComboVatPercent,
            s.GiftCardVatPercent,
            s.MembershipVatPercent,
            s.InvoiceRequestWindowDays,
            [.. s.GiftCardDenominations],
            s.GiftCardMinAmount,
            s.GiftCardMaxAmount,
            s.GiftCardValidityMonths,
            s.GiftCardRefundExtensionDays
        );
}
